import { mkdir, copyFile, cp, readFile, writeFile, readdir } from 'node:fs/promises';
const target = new URL('../public/vendor/katex/', import.meta.url);
const source = new URL('../node_modules/katex/', import.meta.url);
await mkdir(target, {recursive:true});
for (const name of ['katex.mjs','katex.min.css']) await copyFile(new URL('dist/'+name, source),new URL(name,target));
await cp(new URL('dist/fonts/',source),new URL('fonts/',target),{recursive:true});
await copyFile(new URL('LICENSE',source),new URL('LICENSE',target));
const assets=['/vendor/katex/katex.mjs','/vendor/katex/katex.min.css',...(await readdir(new URL('fonts/',target))).map(f=>'/vendor/katex/fonts/'+f)];
await writeFile(new URL('../public/math-assets.js',import.meta.url),`// Generated by scripts/vendor-math.mjs\nself.MATH_ASSETS = ${JSON.stringify(assets,null,2)};\n`);
console.log('Copied KaTeX runtime, fonts, license and offline asset list.');
